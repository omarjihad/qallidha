// Этот файл читают и игра, и бот (сообщения об оплате), поэтому здесь не должно быть ничего браузерного.

function plural(n, one, few, many) {
  const a = Math.abs(Number(n) || 0) % 100;
  const b = a % 10;
  if (a > 10 && a < 20) return many;
  if (b > 1 && b < 5) return few;
  if (b === 1) return one;
  return many;
}

